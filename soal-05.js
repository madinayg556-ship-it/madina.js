// Function untuk menghitung luas persegi panjang
function hitungLuasPersegiPanjang(panjang, lebar) {
    const luas = panjang * lebar;
    return luas;
}

// Memanggil function
const hasil = hitungLuasPersegiPanjang(10, 5);

// Menampilkan hasil
console.log("Luas persegi panjang:", hasil);